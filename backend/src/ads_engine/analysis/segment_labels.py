"""LinkedIn's en_US industry names by URN.

From ``GET /v2/industryTaxonomyVersions/DEFAULT/industries`` (industry taxonomy ``DEFAULT``).
"""

SEGMENT_VALUE_LABELS: Final[Mapping[str, Mapping[str, str]]] = MappingProxyType(
    {
        "job_function": _JOB_FUNCTIONS,
        "seniority": _SENIORITIES,
        "industry": _INDUSTRIES,
    }
)
"""LinkedIn's standardized en_US names by stored facet, then by the stored value's URN.

The keys are the facet names ``fact_segment_window`` stores. Both levels are read-only.
"""


def segment_value_label(facet: str, value: str) -> str:
    """Return LinkedIn's standardized name of a stored demographic segment value.

    Args:
        facet: The stored facet: ``job_function``, ``seniority`` or ``industry``.
        value: The stored segment value, LinkedIn's standardized URN for it, for example
            ``urn:li:seniority:6``.

    Returns:
        The name LinkedIn's Standardized Data gives ``value`` (``Director``), or ``value``
        itself, unchanged, when that data names no such value: an unknown or newer code, an
        unknown facet, or a value that is no standardized URN.
    """
    labels = SEGMENT_VALUE_LABELS.get(facet)
    if labels is None:
        return value
    return labels.get(value, value)
